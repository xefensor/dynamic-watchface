#!/usr/bin/env python3
"""Generate exact baseline descents using the SDK's FreeType MONO load mode.

Run with the Pebble SDK Python environment, or install freetype-py. This only
regenerates/checks a committed rendering asset; ordinary builds need no Python
font packages. The packaged-font audit independently checks the resulting PFO
glyphs against this table.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import freetype

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "resources/fonts/RobotoCondensed-Bold.ttf"
HEADER = ROOT / "src/c/generated_body_metrics.h"
POINTS = (14, 16, 20, 24, 26, 28, 32)
WILDCARD = 0x25AF


def build():
    face = freetype.Face(str(FONT))
    indices = {codepoint: index for codepoint, index in face.get_chars() if index != 0}
    # Pebble fontgen always adds its wildcard using glyph zero.
    indices[WILDCARD] = 0
    codepoints = sorted(indices)
    rows = [[] for _ in codepoints]
    flags = freetype.FT_LOAD_RENDER | freetype.FT_LOAD_MONOCHROME | freetype.FT_LOAD_TARGET_MONO
    for point in POINTS:
        face.set_pixel_sizes(0, point)
        for at, codepoint in enumerate(codepoints):
            face.load_glyph(indices[codepoint], flags)
            descent = face.glyph.bitmap.rows - face.glyph.bitmap_top
            assert -128 <= descent <= 127
            rows[at].append(descent)
    sha = hashlib.sha256(FONT.read_bytes()).hexdigest()
    lines = [
        "// Generated by scripts/generate-body-metrics.py; do not edit.",
        "// Roboto Condensed Bold, Copyright 2011 The Roboto Project Authors.",
        "// Font-derived data: SIL Open Font License 1.1; see resources/fonts/OFL-RobotoCondensed.txt.",
        "// Source TTF SHA256: " + sha,
        "#pragma once", "", "#include <stddef.h>", "#include <stdint.h>", "",
        "#define BODY_METRIC_COUNT " + str(len(codepoints)),
        "#define BODY_METRIC_POINT_COUNT " + str(len(POINTS)),
        '#define BODY_FONT_SOURCE_SHA256 "' + sha + '"',
        "static const uint8_t body_metric_points[BODY_METRIC_POINT_COUNT] = {" +
        ",".join(map(str, POINTS)) + "};",
        "static const uint16_t body_metric_codepoints[BODY_METRIC_COUNT] = {",
    ]
    for at in range(0, len(codepoints), 12):
        lines.append("  " + ",".join("0x%04x" % cp for cp in codepoints[at:at + 12]) + ",")
    lines.extend(["};", "static const int8_t body_metric_descents[BODY_METRIC_COUNT][BODY_METRIC_POINT_COUNT] = {"])
    for row in rows:
        lines.append("  {" + ",".join(map(str, row)) + "},")
    lines.extend([
        "};", "",
        "static inline uint32_t body_metric_next_codepoint(const unsigned char **cursor) {",
        "  const unsigned char *s = *cursor;",
        "  uint32_t result = *s++;",
        "  unsigned tails = 0;",
        "  if (result >= 0xc2 && result <= 0xdf) { tails = 1; result &= 0x1f; }",
        "  else if (result >= 0xe0 && result <= 0xef) { tails = 2; result &= 0x0f; }",
        "  else if (result >= 0xf0 && result <= 0xf4) { tails = 3; result &= 0x07; }",
        "  else if (result >= 0x80) { result = 0xfffd; }",
        "  for (unsigned i = 0; i < tails; ++i) {",
        "    if ((*s & 0xc0) != 0x80) { *cursor = s; return 0xfffd; }",
        "    result = (result << 6) | (*s++ & 0x3f);",
        "  }",
        "  *cursor = s;",
        "  return result;",
        "}", "",
        "static inline size_t body_metric_index(uint32_t codepoint) {",
        "  size_t low = 0, high = BODY_METRIC_COUNT;",
        "  while (low < high) {",
        "    const size_t middle = low + (high - low) / 2;",
        "    if (body_metric_codepoints[middle] < codepoint) { low = middle + 1; }",
        "    else { high = middle; }",
        "  }",
        "  if (low < BODY_METRIC_COUNT && body_metric_codepoints[low] == codepoint) { return low; }",
        "  return BODY_METRIC_COUNT - 1; // U+25AF wildcard is the last stored codepoint.",
        "}", "",
        "// Maximum visible ink below the baseline. Point is the exact resource size.",
        "static inline int body_text_descent(const char *utf8, int point) {",
        "  unsigned column = 0;",
        "  while (column < BODY_METRIC_POINT_COUNT && body_metric_points[column] != point) { ++column; }",
        "  if (utf8 == NULL || column == BODY_METRIC_POINT_COUNT) { return 0; }",
        "  int maximum = 0;",
        "  const unsigned char *cursor = (const unsigned char *)utf8;",
        "  while (*cursor) {",
        "    const uint32_t codepoint = body_metric_next_codepoint(&cursor);",
        "    const int descent = body_metric_descents[body_metric_index(codepoint)][column];",
        "    if (descent > maximum) { maximum = descent; }",
        "  }",
        "  return maximum;",
        "}", "",
    ])
    assert codepoints[-1] == WILDCARD
    return "\n".join(lines), {
        "fontSha256": sha,
        "fontCodepointCount": len(indices) - 1,
        "metricCodepointCountIncludingWildcard": len(codepoints),
        "pointSizes": list(POINTS),
        "freeTypeVersion": list(freetype.version()),
        "loadMode": "FT_LOAD_RENDER | FT_LOAD_MONOCHROME | FT_LOAD_TARGET_MONO",
        "baselinePx": "point size",
        "minimumBitmapDescentPx": min(min(row) for row in rows),
        "maximumBitmapDescentPx": max(max(row) for row in rows),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()
    generated, info = build()
    if args.check:
        if not HEADER.is_file() or HEADER.read_text() != generated:
            raise SystemExit("Generated body metrics are stale; rerun scripts/generate-body-metrics.py")
    else:
        HEADER.write_text(generated)
    if args.json:
        print(json.dumps({"result": "PASS", **info}, indent=2))
    else:
        print(("Verified" if args.check else "Generated") + " " + str(HEADER.relative_to(ROOT)))


if __name__ == "__main__":
    main()
