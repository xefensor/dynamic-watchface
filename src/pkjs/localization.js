var LANGUAGES = Object.keys(MESSAGES);
var LITERALS = Object.create(null);
Object.keys(MESSAGES.en).forEach(function(key) { LITERALS[MESSAGES.en[key]] = key; });

function normalizeLanguage(locale) {
  if (typeof locale !== 'string') { return ''; }
  var base = locale.trim().toLowerCase().split(/[.@]/)[0].replace(/_/g, '-').split('-')[0];
  if (base === 'nb' || base === 'nn') { base = 'no'; }
  return LANGUAGES.indexOf(base) >= 0 ? base : '';
}
function resolveLanguage(watchLanguage, phoneLanguage) {
  return normalizeLanguage(watchLanguage) || normalizeLanguage(phoneLanguage) || 'en';
}
function t(key, language, params) {
  var resolved = Object.prototype.hasOwnProperty.call(MESSAGES.en, key) ? key :
      Object.prototype.hasOwnProperty.call(LITERALS, key) ? LITERALS[key] : null;
  var row = MESSAGES[resolveLanguage(language)];
  var text = resolved ? row[resolved] || MESSAGES.en[resolved] : String(key);
  return text.replace(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g, function(match, name) {
    return params && Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match;
  });
}
function translateConfig(config, language) {
  function clone(value, type) {
    if (Array.isArray(value)) { return value.map(function(item) { return clone(item, type); }); }
    if (!value || typeof value !== 'object') { return value; }
    var result = {};
    type = value.type || type;
    Object.keys(value).forEach(function(key) {
      if ((key === 'label' || key === 'description' || key === 'defaultValue' &&
          ['text','heading','submit'].indexOf(type) >= 0) && typeof value[key] === 'string') {
        result[key] = t(value[key], language);
      } else { result[key] = clone(value[key], type); }
    });
    return result;
  }
  return clone(config, '');
}

